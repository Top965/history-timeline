/**
 * Generates supabase/seed.sql from supabase/seed-data/content.json.
 *
 *   npm run db:seed:build          write the file
 *   npm run db:seed:check          fail if the committed file is out of date (CI)
 *
 * The SQL is idempotent: it upserts by slug, so it can be re-run on a live database.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { seedSchema, type SeedData } from "./schema";

const root = resolve(import.meta.dirname, "../..");
const contentPath = resolve(root, "supabase/seed-data/content.json");
const seedPath = resolve(root, "supabase/seed.sql");

const q = (v: string | null | undefined): string => (v == null ? "null" : `'${v.replaceAll("'", "''")}'`);
const n = (v: number | null | undefined): string => (v == null ? "null" : String(v));
const b = (v: boolean): string => (v ? "true" : "false");
const arr = (v: string[]): string => (v.length ? `array[${v.map(q).join(", ")}]` : "'{}'::text[]");
const eventId = (slug: string) => `(select id from public.events where slug = ${q(slug)})`;

export function buildSeedSql(data: SeedData): string {
  const out: string[] = [];
  const emit = (s: string) => out.push(s);

  emit("-- GENERATED by scripts/seed/build-seed.ts from supabase/seed-data/content.json. Do not edit by hand.");
  emit("-- Seed: the approved prototype's eras, events, topics and the World War I story.");
  emit("begin;");
  emit("");

  emit("-- Eras");
  for (const e of data.eras) {
    emit(
      `insert into public.eras (slug, start_year, end_year, color_token, sort_order) values (${q(e.slug)}, ${n(e.startYear)}, ${n(e.endYear)}, ${q(e.colorToken)}, ${n(e.sortOrder)})\n` +
        `  on conflict (slug) do update set start_year = excluded.start_year, end_year = excluded.end_year, color_token = excluded.color_token, sort_order = excluded.sort_order;`,
    );
    for (const [locale, t] of Object.entries(e.translations)) {
      emit(
        `insert into public.era_translations (era_id, locale, name, keywords) values ((select id from public.eras where slug = ${q(e.slug)}), ${q(locale)}, ${q(t.name)}, ${arr(t.keywords)})\n` +
          `  on conflict (era_id, locale) do update set name = excluded.name, keywords = excluded.keywords;`,
      );
    }
  }
  emit("");

  emit("-- Events");
  for (const e of data.events) {
    emit(
      `insert into public.events (slug, start_year, end_year, is_approximate, importance, wikidata_id, status, published_at) values (${q(e.slug)}, ${n(e.startYear)}, ${n(e.endYear)}, ${b(e.isApproximate)}, ${n(e.importance)}, ${q(e.wikidataId)}, 'published', now())\n` +
        `  on conflict (slug) do update set start_year = excluded.start_year, end_year = excluded.end_year, is_approximate = excluded.is_approximate, importance = excluded.importance, wikidata_id = coalesce(excluded.wikidata_id, public.events.wikidata_id);`,
    );
    for (const [locale, t] of Object.entries(e.translations)) {
      emit(
        `insert into public.event_translations (event_id, locale, title, summary, place_label, media_hint, keywords) values (${eventId(e.slug)}, ${q(locale)}, ${q(t.title)}, ${q(t.summary)}, ${q(t.placeLabel)}, ${q(t.mediaHint)}, ${arr(t.keywords)})\n` +
          `  on conflict (event_id, locale) do update set title = excluded.title, summary = excluded.summary, place_label = excluded.place_label, media_hint = excluded.media_hint, keywords = excluded.keywords;`,
      );
    }
  }
  emit("");

  emit("-- Topics");
  for (const t of data.topics) {
    const topicId = `(select id from public.topics where slug = ${q(t.slug)})`;
    emit(
      `insert into public.topics (slug, start_year, end_year, is_approximate, is_sensitive, status, published_at) values (${q(t.slug)}, ${n(t.startYear)}, ${n(t.endYear)}, ${b(t.isApproximate)}, ${b(t.isSensitive)}, 'published', now())\n` +
        `  on conflict (slug) do update set start_year = excluded.start_year, end_year = excluded.end_year, is_approximate = excluded.is_approximate, is_sensitive = excluded.is_sensitive;`,
    );
    for (const [locale, tr] of Object.entries(t.translations)) {
      // A translation may carry only a name for now; its summary falls back to English until step 3.
      emit(
        `insert into public.topic_translations (topic_id, locale, name, summary, keywords) values (${topicId}, ${q(locale)}, ${q(tr.name)}, ${q(tr.summary)}, ${arr(tr.keywords)})\n` +
          `  on conflict (topic_id, locale) do update set name = excluded.name, summary = excluded.summary, keywords = excluded.keywords;`,
      );
    }
    emit(`delete from public.topic_events where topic_id = ${topicId};`);
    t.events.forEach((slug, i) => {
      emit(
        `insert into public.topic_events (topic_id, event_id, sort_order) values (${topicId}, ${eventId(slug)}, ${i + 1});`,
      );
    });
  }
  emit("");

  emit("-- Stories");
  for (const s of data.stories) {
    const storyId = `(select id from public.stories where event_id = ${eventId(s.event)} and locale = ${q(s.locale)})`;
    emit(
      `update public.events set start_date = ${q(s.startDate)}, end_date = ${q(s.endDate)} where slug = ${q(s.event)};`,
    );
    emit(
      `insert into public.stories (event_id, locale, layout, dek, footnote, status, drafted_by, published_at) values (${eventId(s.event)}, ${q(s.locale)}, ${q(s.layout)}, ${q(s.dek)}, ${q(s.footnote)}, 'published', 'claude', now())\n` +
        `  on conflict (event_id, locale) do update set layout = excluded.layout, dek = excluded.dek, footnote = excluded.footnote;`,
    );
    emit(
      `update public.event_translations set media_hint = ${q(s.heroHint)} where event_id = ${eventId(s.event)} and locale = ${q(s.locale)};`,
    );
    for (const table of [
      "story_key_dates",
      "story_stats",
      "story_chapters",
      "story_sides",
      "story_people",
      "story_related",
    ]) {
      emit(`delete from public.${table} where story_id = ${storyId};`);
    }
    s.stats.forEach((st, i) => {
      emit(
        `insert into public.story_stats (story_id, sort_order, value_label, description) values (${storyId}, ${i + 1}, ${q(st.value)}, ${q(st.description)});`,
      );
    });
    s.chapters.forEach((c, i) => {
      emit(
        `insert into public.story_chapters (story_id, sort_order, title, period_label, paragraphs, figure_kind, figure_caption, shows_sides) values (${storyId}, ${i + 1}, ${q(c.title)}, ${q(c.period)}, ${arr(c.paragraphs)}, ${q(c.figure.kind)}, ${q(c.figure.caption)}, ${b(c.showsSides)});`,
      );
    });
    s.keyDates.forEach((d, i) => {
      emit(
        `insert into public.story_key_dates (story_id, sort_order, date, label, chapter_order) values (${storyId}, ${i + 1}, ${q(d.date)}, ${q(d.label)}, ${n(d.chapter)});`,
      );
    });
    s.sides.forEach((side, i) => {
      emit(
        `insert into public.story_sides (story_id, sort_order, name) values (${storyId}, ${i + 1}, ${q(side.name)});`,
      );
      const sideId = `(select id from public.story_sides where story_id = ${storyId} and sort_order = ${i + 1})`;
      side.members.forEach((m, j) => {
        emit(
          `insert into public.story_side_members (side_id, sort_order, name, note) values (${sideId}, ${j + 1}, ${q(m.name)}, ${q(m.note)});`,
        );
      });
    });
    s.people.forEach((p, i) => {
      emit(
        `insert into public.story_people (story_id, sort_order, name, description, initials) values (${storyId}, ${i + 1}, ${q(p.name)}, ${q(p.description)}, ${q(p.initials)});`,
      );
    });
    s.related.forEach((slug, i) => {
      emit(
        `insert into public.story_related (story_id, related_event_id, sort_order) values (${storyId}, ${eventId(slug)}, ${i + 1});`,
      );
    });
  }
  emit("");
  emit("commit;");
  return out.join("\n") + "\n";
}

function main() {
  const data = seedSchema.parse(JSON.parse(readFileSync(contentPath, "utf8")));
  const sql = buildSeedSql(data);
  if (process.argv.includes("--check")) {
    const current = readFileSync(seedPath, "utf8");
    if (current !== sql) {
      console.error("supabase/seed.sql is out of date. Run: npm run db:seed:build");
      process.exit(1);
    }
    console.log("supabase/seed.sql is up to date.");
    return;
  }
  writeFileSync(seedPath, sql);
  console.log(
    `Wrote supabase/seed.sql: ${data.eras.length} eras, ${data.events.length} events, ${data.topics.length} topics, ${data.stories.length} stories.`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
